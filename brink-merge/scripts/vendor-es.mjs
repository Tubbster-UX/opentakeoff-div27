#!/usr/bin/env node
// Regenerates src/vendor/esEnums.generated.ts from an EasySchematic checkout:
// the live CURRENT_SCHEMA_VERSION and the strict enum key lists the editor
// validates against (DEVICE_TYPE_TO_CATEGORY, SIGNAL_LABELS, CONNECTOR_LABELS).
// brink-merge never imports EasySchematic at runtime; this copy is the seam.
//
//   node scripts/vendor-es.mjs --es <path to EasySchematic checkout>
//   node scripts/vendor-es.mjs --es <path> --check   (exit 1 when stale)
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const args = process.argv.slice(2);
const esDir = args[args.indexOf("--es") + 1];
if (!args.includes("--es") || !esDir) {
  console.error("usage: node scripts/vendor-es.mjs --es <EasySchematic checkout> [--check]");
  process.exit(2);
}
const check = args.includes("--check");
const read = (rel) => readFileSync(join(esDir, rel), "utf8");

const version = Number(/export const CURRENT_SCHEMA_VERSION\s*=\s*(\d+)/.exec(read("src/migrations.ts"))?.[1]);
if (!Number.isInteger(version)) throw new Error("CURRENT_SCHEMA_VERSION not found in src/migrations.ts");

/** Keys of `export const NAME ... = { ... };` — one key per line, as ES writes them. */
function objectKeys(src, name) {
  const start = src.search(new RegExp(`export const ${name}\\b[^=]*=\\s*\\{`));
  if (start < 0) throw new Error(`${name} not found`);
  const body = src.slice(src.indexOf("{", start) + 1, src.indexOf("\n};", start));
  const keys = [];
  for (const line of body.split("\n")) {
    const m = /^\s*(?:"([^"]+)"|'([^']+)'|([A-Za-z_$][\w$]*))\s*:/.exec(line);
    if (m) keys.push(m[1] ?? m[2] ?? m[3]);
  }
  if (!keys.length) throw new Error(`${name} has no keys`);
  return keys;
}

const deviceTypes = objectKeys(read("src/deviceTypeCategories.ts"), "DEVICE_TYPE_TO_CATEGORY");
const types = read("src/types.ts");
const signalTypes = objectKeys(types, "SIGNAL_LABELS");
const connectorTypes = objectKeys(types, "CONNECTOR_LABELS");
let commit = "unknown";
try { commit = execFileSync("git", ["-C", esDir, "rev-parse", "HEAD"], { encoding: "utf8" }).trim(); } catch { /* not a git checkout */ }

const list = (xs) => xs.map((x) => `  ${JSON.stringify(x)},`).join("\n");
const out = `// GENERATED by scripts/vendor-es.mjs. Do not edit by hand.
// Source: EasySchematic (github.com/duremovich/EasySchematic, AGPL-3.0) commit ${commit}
//   src/migrations.ts            CURRENT_SCHEMA_VERSION
//   src/deviceTypeCategories.ts  DEVICE_TYPE_TO_CATEGORY keys
//   src/types.ts                 SIGNAL_LABELS / CONNECTOR_LABELS keys

export const ES_SOURCE_COMMIT = ${JSON.stringify(commit)};
export const CURRENT_SCHEMA_VERSION = ${version};

export const DEVICE_TYPES = [
${list(deviceTypes)}
] as const;

export const SIGNAL_TYPES = [
${list(signalTypes)}
] as const;

export const CONNECTOR_TYPES = [
${list(connectorTypes)}
] as const;
`;

const target = join(dirname(fileURLToPath(import.meta.url)), "../src/vendor/esEnums.generated.ts");
if (check) {
  let current = "";
  try { current = readFileSync(target, "utf8"); } catch { /* missing */ }
  if (current !== out) {
    console.error(`src/vendor/esEnums.generated.ts is stale against ${esDir}; run without --check`);
    process.exit(1);
  }
  console.log(`vendored ES enums current (schema v${version}, ${commit.slice(0, 7)})`);
} else {
  writeFileSync(target, out);
  console.log(`wrote src/vendor/esEnums.generated.ts: schema v${version}, ${deviceTypes.length} device types, ${signalTypes.length} signal types, ${connectorTypes.length} connector types (${commit.slice(0, 7)})`);
}
